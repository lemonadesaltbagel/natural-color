#!/usr/bin/env python3
"""Package the desktop app (.app + .dmg on macOS, .exe on Windows) with PyInstaller.

    python tool/ncseal.py build --out dist/app/natural-color --data --key-mode embedded
    python tool/build_app.py --sealed dist/app/natural-color --version 2.1.0

The sealed tree is shipped as plain files: its framework .py, the .ncs
ciphertext, the manifest and the embedded key.  The launcher puts it on
sys.path, so the vault import hook decrypts the core from disk exactly as in a
sealed release.  PyInstaller still analyses the *plaintext* source (`--source`,
default this repository) to find every library the core needs, and then every
naturalcolor module is removed from its bundle again; the build fails if any
of them survives, if the tree is not an embedded-key build, or if the packaged
app cannot render through the core (`--selftest`).
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NAME = "Natural Color"
BUNDLE_ID = "io.github.lemonadesaltbagel.naturalcolor"
#: development-only modules: never analysed into the app
DEV_MODULES = ["naturalcolor.calibrate", "naturalcolor.verify", "naturalcolor.attribute",
               "naturalcolor.io.ref"]

LAUNCHER = '''\
import os, sys
sys.dont_write_bytecode = True                     # the bundle is read-only
base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(base, "nc"))       # the sealed tree, decrypted by its import hook
from naturalcolor.app import main
raise SystemExit(main())
'''

SPEC = '''\
# generated by tool/build_app.py
import sys
from PyInstaller.utils.hooks import collect_submodules

DEV = {dev!r}
hidden = [m for m in collect_submodules("naturalcolor")
          if not any(m == d or m.startswith(d + ".") for d in DEV)]
a = Analysis([{launcher!r}], pathex=[{source!r}],
             hiddenimports=hidden + ["webview"],
             datas={datas!r},
             excludes=DEV + ["tkinter", "matplotlib", "IPython", "pytest"],
             noarchive=False)
# the plaintext core was only analysed for its imports: it must not ship
a.pure = [e for e in a.pure if not (e[0] == "naturalcolor" or e[0].startswith("naturalcolor."))]
pyz = PYZ(a.pure)
if sys.platform == "darwin":
    exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={name!r}, console=False,
              icon={icns!r}, argv_emulation=False)
    coll = COLLECT(exe, a.binaries, a.datas, name={name!r})
    app = BUNDLE(coll, name={name!r} + ".app", icon={icns!r}, bundle_identifier={bundle!r},
                 info_plist={{"CFBundleShortVersionString": {version!r},
                              "CFBundleVersion": {version!r},
                              "NSHighResolutionCapable": True,
                              "LSMinimumSystemVersion": "12.0"}})
else:
    exe = EXE(pyz, a.scripts, a.binaries, a.datas, [], name={name!r}, console=False,
              icon={ico!r}, upx=False)
'''


def make_icons(work: Path):
    """The favicon's three overlapping R/G/B discs on a grey tile, as .icns and .ico."""
    from PIL import Image, ImageDraw
    n = 1024
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((40, 40, n - 40, n - 40), radius=200, fill=(119, 119, 119, 255))
    layer = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    for (cx, cy), col in (((384, 416), (238, 85, 85)), ((640, 416), (68, 204, 102)),
                          ((512, 640), (85, 136, 255))):
        disc = Image.new("RGBA", (n, n), (0, 0, 0, 0))
        ImageDraw.Draw(disc).ellipse((cx - 218, cy - 218, cx + 218, cy + 218), fill=col + (217,))
        layer = Image.alpha_composite(layer, disc)
    im = Image.alpha_composite(im, layer)
    png, icns, ico = work / "icon.png", work / "icon.icns", work / "icon.ico"
    im.save(png)
    im.save(ico, sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    if sys.platform == "darwin":
        iconset = work / "icon.iconset"
        iconset.mkdir(exist_ok=True)
        for s in (16, 32, 128, 256, 512):
            im.resize((s, s), Image.LANCZOS).save(iconset / f"icon_{s}x{s}.png")
            im.resize((2 * s, 2 * s), Image.LANCZOS).save(iconset / f"icon_{s}x{s}@2x.png")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(icns)], check=True)
    return (str(icns) if icns.exists() else None), str(ico)


def check_sealed(sealed: Path):
    manifest = sealed / "naturalcolor" / "vault" / "manifest.json"
    if not manifest.is_file():
        raise SystemExit(f"{sealed} is not a sealed build (no {manifest.name})")
    mode = json.loads(manifest.read_text()).get("key_mode")
    if mode != "embedded" or not (sealed / "naturalcolor" / "vault" / "_k.py").is_file():
        raise SystemExit(f"{sealed} must be sealed with --key-mode embedded (got {mode!r}): "
                         "the app has to run without a key from the user")
    for d in ("color", "model"):
        stray = sorted((sealed / "naturalcolor" / d).rglob("*.py"))
        if stray:
            raise SystemExit(f"plaintext core in the sealed tree: {stray[0]}")


def check_pyz(build: Path):
    """Fail when any naturalcolor module made it into the frozen archive."""
    from PyInstaller.archive.readers import ZlibArchiveReader
    pyzs = sorted(build.rglob("*.pyz"))
    if not pyzs:
        raise SystemExit("no PYZ archive found to inspect")
    for p in pyzs:
        names = list(ZlibArchiveReader(str(p)).toc)
        leaked = [n for n in names if n == "naturalcolor" or n.startswith("naturalcolor.")]
        if leaked:
            raise SystemExit(f"{p.name} contains plaintext naturalcolor modules: {leaked[:5]}")
        print(f"  {p.name}: {len(names)} modules, none from naturalcolor")


def stage_tree(sealed: Path, dest: Path):
    """The sealed tree minus caches, ready to be shipped as data."""
    if dest.exists():
        shutil.rmtree(dest)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "dist", "tool", ".git")
    for part in ("naturalcolor", "params", "data"):
        if (sealed / part).exists():
            shutil.copytree(sealed / part, dest / part, ignore=ignore)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="build_app", description=__doc__.splitlines()[0])
    ap.add_argument("--sealed", required=True, help="an embedded-key sealed build (ncseal build)")
    ap.add_argument("--source", default=str(REPO), help="plaintext tree, analysed for imports only")
    ap.add_argument("--version", default="0.0.0")
    ap.add_argument("--out", default=str(REPO / "dist" / "app"))
    a = ap.parse_args(argv)

    sealed, out = Path(a.sealed).resolve(), Path(a.out).resolve()
    check_sealed(sealed)
    work = out / "work"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    stage_tree(sealed, work / "nc")
    (work / "launcher.py").write_text(LAUNCHER)
    icns, ico = make_icons(work)
    datas = [(str(work / "nc" / p), f"nc/{p}") for p in ("naturalcolor", "params", "data")
             if (work / "nc" / p).exists()]
    spec = work / "natural-color.spec"
    spec.write_text(SPEC.format(dev=DEV_MODULES, launcher=str(work / "launcher.py"),
                                source=str(Path(a.source).resolve()), datas=datas, name=NAME,
                                icns=icns, ico=ico, bundle=BUNDLE_ID, version=a.version))

    print(f"building {NAME} {a.version} for {sys.platform}/{platform.machine()} ...")
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(out / "pyi-dist"), "--workpath", str(work / "pyi-build"),
                    str(spec)], check=True)
    check_pyz(work / "pyi-build")

    arch = {"arm64": "arm64", "aarch64": "arm64"}.get(platform.machine().lower(), "x64")
    if sys.platform == "darwin":
        app = out / "pyi-dist" / f"{NAME}.app"
        binary = app / "Contents" / "MacOS" / NAME
    else:
        binary = out / "pyi-dist" / f"{NAME}.exe"
    print("self-test of the packaged app ...")
    r = subprocess.run([str(binary), "--selftest"], capture_output=True, text=True, timeout=600)
    print(textwrap.indent((r.stdout or "") + (r.stderr or ""), "  "))
    if r.returncode != 0:
        raise SystemExit(f"the packaged app failed its self-test (exit {r.returncode})")

    if sys.platform == "darwin":
        stage = work / "dmg"
        stage.mkdir()
        shutil.copytree(app, stage / app.name, symlinks=True)
        os.symlink("/Applications", stage / "Applications")
        artifact = out / f"Natural-Color-{a.version}-macOS-{arch}.dmg"
        artifact.unlink(missing_ok=True)
        subprocess.run(["hdiutil", "create", "-volname", NAME, "-srcfolder", str(stage),
                        "-ov", "-format", "UDZO", str(artifact)], check=True)
    else:
        artifact = out / f"Natural-Color-{a.version}-Windows-{arch}.exe"
        shutil.copy2(binary, artifact)
    print(f"\n{artifact}  ({artifact.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
