def cmd_inplace(args):
    backup_dir = REPO / "_backup"
    backup_dir.mkdir(exist_ok=True)
    tarball = backup_dir / f"natural-color-{time.strftime('%Y%m%d-%H%M%S')}.tar.gz"
    print(f"backing up to {tarball}")
    with tarfile.open(tarball, "w:gz") as tf:
        for p in sorted(REPO.rglob("*")):
            rel = p.relative_to(REPO)
            if rel.parts[0] in {".git", ".venv", "dist", "_backup", "_scratch", "__pycache__"}:
                continue
            tf.add(p, arcname=rel.as_posix(), recursive=False)

    master = _key_from_args(args)
    bound = bool(args.bind)
    binding = _kdf.host_secret() if bound else b""
    if bound and not binding:
        raise SystemExit("--bind requested but this host has no stable identifier")
    vault_dir = REPO / "naturalcolor" / "vault"
    manifest = _manifest_stub(master, bound, args.key_mode)

    for fullname in args.include or PROTECTED:
        src = module_source(fullname)
        source = src.read_bytes()
        blob = seal_blob(master, "mod", fullname, source, bound=bound, binding=binding)
        rel, pkg_rel = module_rel(fullname), module_pkg_rel(fullname)
        (vault_dir.parent / pkg_rel.with_suffix(".ncs")).write_bytes(blob)
        src.unlink()
        manifest["modules"][fullname] = {
            "file": pkg_rel.with_suffix(".ncs").as_posix(), "kind": "mod",
            "sha256": hashlib.sha256(source).hexdigest(),
            "bytes": len(source), "flags": _format.describe(blob)["flags"]}
        print(f"  sealed {fullname}")
    for path in data_files(args.data):
        rel = path.relative_to(REPO)
        payload = path.read_bytes()
        blob = seal_blob(master, "data", rel.as_posix(), payload, bound=bound, binding=binding)
        (REPO / (rel.as_posix() + ".ncs")).write_bytes(blob)
        path.unlink()
        manifest["data"][rel.as_posix()] = {
            "file": rel.as_posix() + ".ncs", "kind": "data",
            "sha256": hashlib.sha256(payload).hexdigest(),
            "bytes": len(payload), "flags": _format.describe(blob)["flags"]}
        print(f"  sealed {rel.as_posix()}")
    (vault_dir / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    if args.key_mode == "embedded":
        write_embedded_key(vault_dir, master)
    else:
        _emit_key(master, args.key_out)
    print(f"\nsealed in place with key {manifest['key_id']}")
    print(f"restore: tar -xzf {tarball}  (or python tool/ncseal.py unseal --root .)")
    return 0


# --------------------------------------------------------------------------
def load_manifest(root):
    p = Path(root) / "naturalcolor" / "vault" / "manifest.json"
    if not p.is_file():
        raise SystemExit(f"{p} not found: {root} is not a sealed tree")
    return json.loads(p.read_text()), Path(root)


def _key_for_tree(root, args):
    if getattr(args, "key", None):
        return parse_key(args.key)
    if getattr(args, "key_file", None):
        return parse_key(Path(args.key_file).read_text())
    embedded = Path(root) / "naturalcolor" / "vault" / "_k.py"
    if embedded.is_file():
        import importlib.util
        spec = importlib.util.spec_from_file_location("_ncseal_k", embedded)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod.material()
    from naturalcolor.vault import master as runtime_master
    return runtime_master()


def _key_from_args(args):
    if getattr(args, "key", None):
        return parse_key(args.key)
    if getattr(args, "key_file", None):
        return parse_key(Path(args.key_file).read_text())
    return secrets.token_bytes(32)


def verify_tree(root, env_extra=None):
    """Decrypt every payload of `root` in a subprocess that imports that tree."""
    code = ("import json,naturalcolor.vault as v;"
            "print(json.dumps(v.verify()))")
    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    env.update(env_extra or {})
    proc = subprocess.run([sys.executable, "-c", code], cwd=str(root),
                          capture_output=True, text=True, env=env)
    for line in reversed(proc.stdout.strip().splitlines()):
        try:
            report = json.loads(line)
        except ValueError:
            continue
        return bool(report.get("ok")), report
    return False, {"error": (proc.stderr or proc.stdout or "no output").strip()[-400:]}


