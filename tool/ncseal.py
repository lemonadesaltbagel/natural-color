def cmd_unseal(args):
    manifest, root = load_manifest(args.root)
    master = _key_for_tree(root, args)
    if manifest.get("key_id") and key_id(master) != manifest["key_id"]:
        raise SystemExit("wrong key: does not match the manifest's key id")
    binding = _kdf.host_secret() if manifest.get("binding") == "machine" else b""
    n = 0
    for fullname, entry in sorted(manifest["modules"].items()):
        blob = (root / "naturalcolor" / entry["file"]).read_bytes()
        source = open_blob(master, "mod", fullname, blob, binding=binding)
        dest = root / module_rel(fullname)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(source)
        (root / "naturalcolor" / entry["file"]).unlink()
        n += 1
        print(f"  restored {fullname}")
    for name, entry in sorted(manifest["data"].items()):
        blob = (root / entry["file"]).read_bytes()
        payload = open_blob(master, "data", name, blob, binding=binding)
        (root / name).write_bytes(payload)
        (root / entry["file"]).unlink()
        n += 1
        print(f"  restored {name}")
    for junk in ((root / "naturalcolor" / "vault" / "manifest.json"),
                 (root / "naturalcolor" / "vault" / "_k.py")):
        junk.unlink(missing_ok=True)
    for cache in root.rglob("__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)
    print(f"\nrestored {n} payloads in {root}")
    return 0


def cmd_status(args):
    root = Path(args.root).resolve()
    manifest, _ = load_manifest(root)
    print(f"tree        {root}")
    print(f"build       {manifest.get('build')}")
    print(f"cipher      {manifest.get('cipher')} / {manifest.get('kdf')}")
    print(f"binding     {manifest.get('binding')}")
    print(f"key mode    {manifest.get('key_mode')} (id {manifest.get('key_id')})")
    print(f"modules     {len(manifest.get('modules') or {})}")
    print(f"data        {len(manifest.get('data') or {})}")
    print()
    print(f"{'payload':<40} {'plain':>8} {'sealed':>8}  flags")
    for group, base in (("modules", root / "naturalcolor"), ("data", root)):
        for name, entry in sorted((manifest.get(group) or {}).items()):
            path = base / entry["file"]
            size = path.stat().st_size if path.is_file() else 0
            d = _format.describe(path.read_bytes()[:64]) if path.is_file() else {}
            flags = "+".join(f for f, on in (("zlib", d.get("compressed")),
                                             ("host", d.get("bound"))) if on)
            print(f"{name:<40} {entry.get('bytes', 0):>8,} {size:>8,}  {flags}")
    print()
    try:
        extra = {"NATURALCOLOR_VAULT_KEY": _key_for_tree(root, args).hex()}
    except Exception:
        extra = {}
    ok, report = verify_tree(root, extra)
    print("verify      OK" if ok else f"verify      FAILED ({report.get('error')})")
    return 0 if ok else 1


def cmd_selftest(args):
    sys.path.insert(0, str(REPO / "tool"))
    import unittest
    import test_vault
    result = unittest.TextTestRunner(verbosity=2).run(
        unittest.defaultTestLoader.loadTestsFromModule(test_vault))
    return 0 if result.wasSuccessful() else 1


# --------------------------------------------------------------------------
def main(argv=None):
    ap = argparse.ArgumentParser(prog="ncseal", description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p):
        p.add_argument("--data", action="store_true", help="also seal params/ and calibrated data")
        p.add_argument("--bind", action="store_true", help="bind ciphertext to this machine")
        p.add_argument("--key", default=None, help="explicit 32-byte key (hex)")
        p.add_argument("--key-file", default=None, help="read the key from a file")
        p.add_argument("--key-out", default=None, help="where to write the key in external mode")
        p.add_argument("--key-mode", choices=("embedded", "external"), default="embedded",
                       help="embedded = key shipped in the build; external = key supplied at run time")
        p.add_argument("--include", action="append", metavar="MODULE",
                       help="seal this module instead of the default set (repeatable)")

    b = sub.add_parser("build", help="build a sealed distribution tree")
    b.add_argument("--out", default="dist/natural-color")
    b.add_argument("--force", action="store_true")
    b.add_argument("--keep-source", action="store_true", help="keep the plaintext .py beside the .ncs")
    b.add_argument("--with-tool", action="store_true", help="copy tool/ into the build")
    b.add_argument("--verify", default=True, action=argparse.BooleanOptionalAction)
    common(b)

    i = sub.add_parser("inplace", help="seal this working tree (writes a backup tarball)")
    common(i)

    u = sub.add_parser("unseal", help="restore plaintext from a sealed tree")
    u.add_argument("--root", required=True)
    u.add_argument("--key", default=None)
    u.add_argument("--key-file", default=None)

    s = sub.add_parser("status", help="describe a sealed tree and verify it")
    s.add_argument("--root", default="dist/natural-color")
    s.add_argument("--key", default=None)
    s.add_argument("--key-file", default=None)

    sub.add_parser("selftest", help="run the crypto test vectors")

    a = ap.parse_args(argv)
    return {"build": cmd_build, "inplace": cmd_inplace, "unseal": cmd_unseal,
            "status": cmd_status, "selftest": cmd_selftest}[a.cmd](a)


if __name__ == "__main__":
    raise SystemExit(main())
