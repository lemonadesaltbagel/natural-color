#!/usr/bin/env python3
"""Seal the colour core into an authenticated, encrypted distribution.

    python tool/ncseal.py build --out dist/natural-color --data
    python tool/ncseal.py status --root dist/natural-color
    python tool/ncseal.py unseal --root dist/natural-color

`build` copies the tree, replaces the protected modules with `.ncs` ciphertext,
optionally does the same for the calibrated parameter files, and writes
`naturalcolor/vault/manifest.json` so the import hook knows what to decrypt.
`unseal` restores plaintext from a build (needs the same key).

The source tree is never modified by `build`; only `inplace` touches it, and it
writes a timestamped tarball under `_backup/` first.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import secrets
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from naturalcolor.vault import _format, _kdf            # noqa: E402
from naturalcolor.vault import open_blob, seal_blob    # noqa: E402

# The colour core: transform math, calibrated curves, camera model.
PROTECTED = [
    "naturalcolor.color.engine",
    "naturalcolor.color.curves",
    "naturalcolor.color.matrices",
    "naturalcolor.color.profiles",
    "naturalcolor.color.icc",
    "naturalcolor.color.whitebalance",
    "naturalcolor.io.demosaic",
    "naturalcolor.io.denoise",
    "naturalcolor.model.camera",
    "naturalcolor.model.post",
    "naturalcolor.model.hdr",
]

# Calibrated data is the other half of the algorithm.
PROTECTED_DATA = [
    "params/*.json",
    "data/gain_curves.json",
]

#: development-only material that must not ship in a release: it needs the
#: vendor reference renders, or it describes the pipeline internals in prose
EXCLUDE_FROM_RELEASE = [
    "naturalcolor/calibrate",
    "naturalcolor/attribute.py",
    "naturalcolor/verify.py",
    "naturalcolor/io/ref.py",
    "docs/PIPELINES.md",
    "docs/PIPELINE-V2.md",
    "docs/DEV.md",
]

COPY_IGNORE = shutil.ignore_patterns(
    "__pycache__", "*.pyc", ".git", ".core-src", ".venv*", "dist", "_backup", "_scratch",
    "*.ncs", "manifest.json", "_k.py", "*.tif", "*.tiff", "*.jpg", "*.jpeg",
)


# --------------------------------------------------------------------------
def key_id(master):
    return _kdf.key_id(master)


def parse_key(text):
    from naturalcolor.vault._keys import _decode
    key = _decode(text)
    if key is None:
        raise SystemExit("key must be 32 bytes as hex (64 chars) or base64")
    return key


def write_embedded_key(vault_dir, master):
    """Store the key as XOR-split words so it does not appear as a plain string."""
    words = [int.from_bytes(master[i:i + 4], "big") for i in range(0, 32, 4)]
    pairs = []
    for w in words:
        b = secrets.randbits(32)
        pairs.append(((w ^ ((b * 0x9E3779B1) & 0xFFFFFFFF)) & 0xFFFFFFFF, b))
    body = ",\n    ".join(f"(0x{a:08X}, 0x{bb:08X})" for a, bb in pairs)
    text = f'''"""Generated by tool/ncseal.py at build time -- do not edit.

The master key for this build, stored as XOR-split 32-bit words. This keeps
the bytes out of `strings` output; it is not a secret from anyone who already
has the loader (see docs/PROTECT.md).
"""
import hashlib as _hashlib

_SPLIT = (
    {body},
)
_CHECK = "{key_id(master)}"


def material():
    out = bytearray()
    for a, b in _SPLIT:
        out += ((a ^ ((b * 0x9E3779B1) & 0xFFFFFFFF)) & 0xFFFFFFFF).to_bytes(4, "big")
    key = bytes(out)
    if _hashlib.sha256(b"ncvault-key\\x00" + key).hexdigest()[:16] != _CHECK:
        raise RuntimeError("vault key material is corrupt (edited _k.py?)")
    return key
'''
    (vault_dir / "_k.py").write_text(text)


def module_source(fullname):
    return REPO / module_rel(fullname)


def module_rel(fullname):
    """Path of the source file, relative to the repository root."""
    return Path(*fullname.split(".")).with_suffix(".py")


def module_pkg_rel(fullname):
    """Path of the sealed blob, relative to the naturalcolor/ package root."""
    return Path(*fullname.split(".")[1:]).with_suffix(".py")


def data_files(with_data):
    if not with_data:
        return []
    out = []
    for pattern in PROTECTED_DATA:
        for p in sorted(REPO.glob(pattern)):
            if p.is_file() and p not in out:
                out.append(p)
    return out


def _manifest_stub(master, bound, key_mode):
    return {
        "version": 1,
        "build": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "cipher": "chacha20-poly1305",
        "kdf": "hkdf-sha256",
        "binding": "machine" if bound else "portable",
        "key_mode": key_mode,
        "key_id": key_id(master),
        "modules": {},
        "data": {},
    }


# --------------------------------------------------------------------------
def cmd_build(args):
    out = Path(args.out).resolve()
    if out == REPO:
        raise SystemExit("refusing to build over the source tree; use `inplace`")
    if out.exists():
        if not args.force:
            raise SystemExit(f"{out} already exists (use --force to replace)")
        shutil.rmtree(out)
    out.parent.mkdir(parents=True, exist_ok=True)

    master = _key_from_args(args)
    bound = bool(args.bind)
    binding = _kdf.host_secret() if bound else b""
    if bound and not binding:
        raise SystemExit("--bind requested but this host has no stable identifier")

    print(f"copying {REPO} -> {out}")
    shutil.copytree(REPO, out, ignore=COPY_IGNORE, symlinks=True)
    if not args.with_tool:
        shutil.rmtree(out / "tool", ignore_errors=True)
    stripped = 0
    for rel in EXCLUDE_FROM_RELEASE:
        target = out / rel
        if target.is_dir():
            shutil.rmtree(target, ignore_errors=True)
            stripped += 1
        elif target.exists():
            target.unlink()
            stripped += 1
    if stripped:
        print(f"  stripped {stripped} development-only path(s) from the release")
    public_readme = REPO / "ci" / "README.md"
    if public_readme.is_file():
        shutil.copy2(public_readme, out / "README.md")
        print("  README.md replaced with the public one (ci/README.md)")

    vault_dir = out / "naturalcolor" / "vault"
    vault_dir.mkdir(parents=True, exist_ok=True)
    manifest = _manifest_stub(master, bound, args.key_mode)

    sealed_total = 0
    for fullname in args.include or PROTECTED:
        src = module_source(fullname)
        if not src.is_file():
            raise SystemExit(f"{src} is missing: build from an unsealed source tree")
        source = src.read_bytes()
        blob = seal_blob(master, "mod", fullname, source, bound=bound, binding=binding)
        rel, pkg_rel = module_rel(fullname), module_pkg_rel(fullname)
        sealed = vault_dir.parent / pkg_rel.with_suffix(".ncs")
        sealed.parent.mkdir(parents=True, exist_ok=True)
        sealed.write_bytes(blob)
        if not args.keep_source:
            (out / rel).unlink(missing_ok=True)
        manifest["modules"][fullname] = {
            "file": pkg_rel.with_suffix(".ncs").as_posix(), "kind": "mod",
            "sha256": hashlib.sha256(source).hexdigest(),
            "bytes": len(source), "flags": _format.describe(blob)["flags"],
        }
        sealed_total += len(blob)
        print(f"  sealed {fullname:<34} {len(source):>6} B -> {len(blob):>6} B")

    for path in data_files(args.data):
        rel = path.relative_to(REPO)
        payload = path.read_bytes()
        blob = seal_blob(master, "data", rel.as_posix(), payload, bound=bound, binding=binding)
        (out / (rel.as_posix() + ".ncs")).write_bytes(blob)
        (out / rel).unlink(missing_ok=True)
        manifest["data"][rel.as_posix()] = {
            "file": rel.as_posix() + ".ncs", "kind": "data",
            "sha256": hashlib.sha256(payload).hexdigest(),
            "bytes": len(payload), "flags": _format.describe(blob)["flags"],
        }
        sealed_total += len(blob)
        print(f"  sealed {rel.as_posix():<34} {len(payload):>6} B -> {len(blob):>6} B")

    (vault_dir / "manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")

    if args.key_mode == "embedded":
        write_embedded_key(vault_dir, master)
    else:
        _emit_key(master, args.key_out)

    print(f"\nbuilt {out}")
    print(f"  {len(manifest['modules'])} modules, {len(manifest['data'])} data files, "
          f"{sealed_total:,} B ciphertext")
    print(f"  key {manifest['key_id']} "
          f"({'machine-bound' if bound else 'portable'}, {args.key_mode})")

    if args.verify:
        ok, report = verify_tree(out, {"NATURALCOLOR_VAULT_KEY": master.hex()})
        print(f"  verify {'OK' if ok else 'FAILED'} "
              f"({len(report.get('modules', []))} modules, {len(report.get('data', []))} data)"
              + ("" if ok else f": {report.get('error') or 'digest mismatch'}"))
        return 0 if ok else 1
    return 0


def _emit_key(master, key_out):
    text = master.hex()
    if key_out:
        p = Path(key_out).resolve()
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text + "\n")
        os.chmod(p, 0o600)
        print(f"\nkey written to {p} (mode 600)")
        print(f"run with: export NATURALCOLOR_VAULT_KEY_FILE={p}")
    else:
        print(f"\n!!! the key is NOT in the build; store it somewhere safe:\n\n    {text}\n")
        print("run with: export NATURALCOLOR_VAULT_KEY=<key>")


